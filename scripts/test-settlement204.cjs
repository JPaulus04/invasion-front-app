const assert=require('node:assert/strict');
require('../src/settlement204.js');
const a=global.LSCSettlement,save=()=>true,m={credits:500,settlementMode:204};
let now=100000;
const act=(k,p)=>{const r=a.action(m,save,k,p,now);assert.ok(r.ok,r.message);};
assert.ok(a.initialize(m,save,now).ok);assert.equal(m.credits,2500);assert.equal(a.workers(m).available,12);
act('assign',{id:'1,0',count:2});act('assign',{id:'0,1',count:2});
assert.equal(a.rates(m).food,3);assert.equal(a.rates(m).materials,4);
act('scout',{id:'2,0'});assert.equal(a.workers(m).available,6);
act('build',{type:'house',path:['-1,0']});assert.equal(a.workers(m).available,4);
now+=20000;a.tick(m,save,now);assert.equal(a.housing(m),16);assert.equal(a.workers(m).available,6);
now+=40000;a.tick(m,save,now);assert.equal(a.workers(m).available,8);assert.ok(a.ready(m,1));
assert.equal(a.income(m),2,'discovery produces no town income');
assert.ok(a.win(m,1));now=m.settlement204.at;
assert.equal(a.income(m),2,'defense alone produces no town income');
assert.equal(a.action(m,save,'welcome',{town:1},now).ok,false);
act('build',{type:'road',path:['2,0','3,0','4,0','5,0']});now+=10000;a.tick(m,save,now);
act('welcome',{town:1});assert.equal(m.settlement204.population,16);assert.equal(a.income(m),4);
assert.equal(a.action(m,save,'welcome',{town:1},now).ok,false,'no duplicate survivors');
assert.equal(a.action(m,save,'demolish',{id:'-1,0'},now).ok,false,'occupied housing protected');
const snapshot=JSON.stringify(m);assert.equal(a.action(m,()=>false,'assign',{id:'1,0',count:3},now).ok,false);assert.equal(JSON.stringify(m),snapshot,'failed saves roll back');
assert.equal(a.action(m,save,'assign',{id:'1,0',count:99},now).ok,false);
act('demolish',{id:'3,0'});assert.equal(a.income(m),2,'disconnected town stops income');assert.equal(m.settlement204.population,16);
act('assign',{id:'1,0',count:0});m.settlement204.food=0;const mat=m.settlement204.materials;now+=60000;a.tick(m,save,now);assert.equal(m.settlement204.population,16);assert.equal(m.settlement204.materials,mat+2,'shortage halves workshop production');
const failed={credits:500};assert.equal(a.initialize(failed,()=>false,now).ok,false);assert.deepEqual(failed,{credits:500});
console.log('PASS settlement204: opening expedition/building, production, defense/connect/housing gate, survivors, disconnection, shortages, save rollback.');
